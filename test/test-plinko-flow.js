import assert from 'node:assert/strict';
import {uiHarness} from './helpers/instantUiHarness.js';
const result=request=>({roundId:request.roundId,game:'plinko',wager:100,rows:8,risk:'high',path:Array(8).fill(0),bucket:0,multiplier:29,payout:2900,profit:2800,balance:3800,multipliers:Array(9).fill(.2)});
const h=uiHarness({onPlay:async request=>{const r=result(request);h.history.unshift(r);return r;}});
await h.controller.show('plinko');
h.submit();await h.flush();
h.step(-1);await h.flush();
assert(!h.node('plinkoBoard').querySelectorAll('rect').some(r=>r.attrs.stroke==='#fff'),'destination must not highlight before landing');
assert(!h.node('instantResult').textContent.includes('2900'),'result must not show before landing');
await h.node('instantRefresh').handlers.click();
assert(!h.node('instantHistory').textContent.includes('2,900'),'history must hide airborne rounds');
h.submit();await h.flush();
assert.equal(h.calls.length,2,'a second drop must start before the first lands');
assert.equal(h.node('plinkoBoard').querySelectorAll('[data-plinko-ball]').length,2,'each active drop has a distinct ball');
assert.notEqual(h.calls[0].roundId,h.calls[1].roundId);
h.step(2000);await h.flush();h.step(2000);await h.flush();
assert.equal(h.node('plinkoBoard').querySelectorAll('[data-plinko-ball]').length,0);
assert(h.node('plinkoBoard').querySelectorAll('rect').some(r=>r.attrs.stroke==='#fff'),'only landed bucket highlights');
assert.equal(h.store.has(h.key),false,'landed requests no longer need recovery');
console.log('Concurrent drops, per-ball landing and no early result reveal passed');
