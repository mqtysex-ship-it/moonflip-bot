import assert from 'node:assert/strict';
import {uiHarness} from './helpers/instantUiHarness.js';
const request={roundId:'00000000-0000-4000-8000-000000000123',wager:30,rows:8,risk:'high'};
const h=uiHarness({pending:request,onPlay:async()=>{const error=new Error('Session expired');error.status=401;throw error;}});
await h.controller.show('plinko');
assert.equal(Number(h.node('instantWager').value),30);
assert.equal(Number(h.node('plinkoRows').value),8);
assert.equal(h.node('plinkoRisk').value,'high');
h.submit();await h.flush();
assert.equal(h.store.get(h.key),JSON.stringify(request),'401 preserves recovery request');
assert.match(h.node('instantMessage').textContent,/Reconnect/);
console.log('Pending Plinko settings and expired-session recovery regressions passed');
